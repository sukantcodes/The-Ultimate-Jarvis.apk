package com.jarvis.assistant.ui.chat

import android.content.Context
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.text.Layout
import android.text.StaticLayout
import android.text.TextPaint
import com.jarvis.assistant.data.model.ChatTurn
import java.io.OutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object ChatExporter {

    private val DATE_FORMAT = SimpleDateFormat("EEE, dd MMM yyyy · HH:mm:ss", Locale.getDefault())

    /**
     * Converts a list of chat turns into a clean, GitHub-Flavored Markdown document.
     */
    fun generateMarkdown(turns: List<ChatTurn>): String {
        val now = DATE_FORMAT.format(Date())
        val sb = StringBuilder()

        sb.append("# ⚡ JARVIS AI — Conversation Transcript\n\n")
        sb.append("> **Exported:** $now  \n")
        sb.append("> **Total Turns:** ${turns.size}  \n")
        sb.append("> **Platform:** Jarvis AI Android Workspace\n\n")
        sb.append("---\n\n")

        for ((index, turn) in turns.withIndex()) {
            val num = index + 1
            sb.append("## Turn $num · You\n\n")
            if (!turn.attachmentName.isNullOrBlank()) {
                sb.append("> 📎 **Attachment:** `${turn.attachmentName}`\n\n")
            }
            sb.append(turn.userTranscript.trim()).append("\n\n")

            sb.append("## 🤖 JARVIS (${turn.formattedTime})\n\n")
            sb.append(turn.jarvisResponse.trim()).append("\n\n")
            sb.append("---\n\n")
        }

        sb.append("\n*Generated by Jarvis AI Assistant*\n")
        return sb.toString()
    }

    /**
     * Generates a paginated vector PDF document of the conversation transcript.
     */
    fun generatePdf(context: Context, turns: List<ChatTurn>, outputStream: OutputStream) {
        val pdfDoc = PdfDocument()

        val pageWidth = 595 // A4 standard width in points
        val pageHeight = 842 // A4 standard height in points
        val margin = 40f
        val contentWidth = (pageWidth - (margin * 2)).toInt()

        val titlePaint = TextPaint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.parseColor("#0F172A")
            textSize = 18f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }

        val metaPaint = TextPaint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.parseColor("#64748B")
            textSize = 10f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        }

        val userHeaderPaint = TextPaint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.parseColor("#0284C7")
            textSize = 12f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }

        val jarvisHeaderPaint = TextPaint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.parseColor("#7C3AED")
            textSize = 12f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }

        val bodyPaint = TextPaint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.parseColor("#1E293B")
            textSize = 10f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        }

        val codePaint = TextPaint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.parseColor("#0F172A")
            textSize = 9f
            typeface = Typeface.create(Typeface.MONOSPACE, Typeface.NORMAL)
        }

        val dividerPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.parseColor("#E2E8F0")
            strokeWidth = 1f
        }

        val cardBgPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.parseColor("#F8FAFC")
            style = Paint.Style.FILL
        }

        var pageNumber = 1
        var pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create()
        var page = pdfDoc.startPage(pageInfo)
        var canvas: Canvas = page.canvas
        var yCursor = margin

        fun drawHeaderAndFooter() {
            // Top rule
            canvas.drawLine(margin, 24f, pageWidth - margin, 24f, dividerPaint)
            // Page numbering at bottom
            val footerText = "JARVIS AI Assistant  ·  Page $pageNumber"
            canvas.drawText(footerText, margin, pageHeight - 20f, metaPaint)
            canvas.drawLine(margin, pageHeight - 28f, pageWidth - margin, pageHeight - 28f, dividerPaint)
        }

        fun checkPageBreak(requiredHeight: Float) {
            if (yCursor + requiredHeight > pageHeight - margin - 20f) {
                drawHeaderAndFooter()
                pdfDoc.finishPage(page)
                pageNumber++
                pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create()
                page = pdfDoc.startPage(pageInfo)
                canvas = page.canvas
                yCursor = margin + 10f
            }
        }

        // Title page header
        canvas.drawText("⚡ JARVIS AI — Conversation Transcript", margin, yCursor + 16f, titlePaint)
        yCursor += 26f
        val now = DATE_FORMAT.format(Date())
        canvas.drawText("Exported: $now  ·  ${turns.size} conversation turns", margin, yCursor + 10f, metaPaint)
        yCursor += 22f
        canvas.drawLine(margin, yCursor, pageWidth - margin, yCursor, dividerPaint)
        yCursor += 16f

        for ((i, turn) in turns.withIndex()) {
            checkPageBreak(70f)

            // User section header
            val userTitle = "You (Turn ${i + 1})"
            canvas.drawText(userTitle, margin, yCursor + 12f, userHeaderPaint)
            yCursor += 18f

            if (!turn.attachmentName.isNullOrBlank()) {
                val attachText = "📎 Attachment: ${turn.attachmentName}"
                canvas.drawText(attachText, margin + 4f, yCursor + 10f, metaPaint)
                yCursor += 16f
            }

            // User body layout
            val userText = turn.userTranscript.trim()
            if (userText.isNotBlank()) {
                val userLayout = StaticLayout.Builder.obtain(userText, 0, userText.length, bodyPaint, contentWidth)
                    .setAlignment(Layout.Alignment.ALIGN_NORMAL)
                    .setLineSpacing(2f, 1f)
                    .build()

                checkPageBreak(userLayout.height.toFloat() + 20f)
                canvas.save()
                canvas.translate(margin, yCursor)
                userLayout.draw(canvas)
                canvas.restore()
                yCursor += userLayout.height + 14f
            }

            // Jarvis section header
            checkPageBreak(60f)
            val jarvisTitle = "JARVIS (${turn.formattedTime})"
            canvas.drawText(jarvisTitle, margin, yCursor + 12f, jarvisHeaderPaint)
            yCursor += 18f

            val jarvisText = turn.jarvisResponse.trim()
            if (jarvisText.isNotBlank()) {
                val isCode = jarvisText.contains("```")
                val activePaint = if (isCode) codePaint else bodyPaint

                val jarvisLayout = StaticLayout.Builder.obtain(jarvisText, 0, jarvisText.length, activePaint, contentWidth)
                    .setAlignment(Layout.Alignment.ALIGN_NORMAL)
                    .setLineSpacing(2f, 1f)
                    .build()

                checkPageBreak(jarvisLayout.height.toFloat() + 20f)
                canvas.save()
                canvas.translate(margin, yCursor)
                jarvisLayout.draw(canvas)
                canvas.restore()
                yCursor += jarvisLayout.height + 18f
            }

            // Turn separator
            checkPageBreak(15f)
            canvas.drawLine(margin, yCursor, pageWidth - margin, yCursor, dividerPaint)
            yCursor += 14f
        }

        drawHeaderAndFooter()
        pdfDoc.finishPage(page)
        pdfDoc.writeTo(outputStream)
        pdfDoc.close()
    }
}
