-- Owner Analytics Dashboard schema.
-- Every table has Row Level Security enabled and NO policies, and all privileges are revoked from the
-- API roles (anon / authenticated). The only way to read or write them is the service role, which is
-- used exclusively inside the Edge Functions (device-telemetry, owner-dashboard). The Android app never
-- holds that key and never queries these tables directly.

-- ── Settings (single row) ────────────────────────────────────────────────────────────────────────
create table public.owner_settings (
  id                   boolean primary key default true check (id),
  ip_retention_days    integer not null default 30  check (ip_retention_days between 1 and 365),
  event_retention_days integer not null default 90  check (event_retention_days between 1 and 730),
  session_ttl_seconds  integer not null default 900 check (session_ttl_seconds between 60 and 3600),
  max_failed_attempts  integer not null default 5   check (max_failed_attempts between 3 and 20),
  lockout_seconds      integer not null default 900 check (lockout_seconds between 60 and 86400)
);
insert into public.owner_settings (id) values (true);

-- ── Devices ──────────────────────────────────────────────────────────────────────────────────────
-- install_id is a random UUID generated by the app on first run. It is NOT derived from IMEI, SIM,
-- phone number, Android ID or any hardware identifier, and it resets if the app data is cleared.
create table public.app_devices (
  id               uuid primary key default gen_random_uuid(),
  install_id       uuid not null unique,
  user_id          uuid references auth.users (id) on delete cascade,
  device_model     text check (char_length(device_model) <= 80),
  android_version  text check (char_length(android_version) <= 32),
  app_version      text check (char_length(app_version) <= 32),
  first_seen_at    timestamptz not null default now(),
  last_seen_at     timestamptz not null default now()
);
create index app_devices_user_idx      on public.app_devices (user_id);
create index app_devices_last_seen_idx on public.app_devices (last_seen_at desc);

-- ── App events (sign-ins / app opens) ────────────────────────────────────────────────────────────
create table public.app_events (
  id          bigint generated always as identity primary key,
  user_id     uuid not null references auth.users (id) on delete cascade,
  device_id   uuid references public.app_devices (id) on delete cascade,
  event_type  text not null check (event_type in ('sign_in', 'app_open')),
  created_at  timestamptz not null default now()
);
create index app_events_created_idx on public.app_events (created_at desc);
create index app_events_type_idx    on public.app_events (event_type, created_at desc);

-- ── IP observations (captured server-side only) ──────────────────────────────────────────────────
create table public.ip_observations (
  id             bigint generated always as identity primary key,
  ip             inet not null,
  user_id        uuid not null references auth.users (id) on delete cascade,
  device_id      uuid not null references public.app_devices (id) on delete cascade,
  first_seen_at  timestamptz not null default now(),
  last_seen_at   timestamptz not null default now(),
  request_count  integer not null default 1,
  unique (ip, user_id, device_id)
);
create index ip_observations_last_seen_idx on public.ip_observations (last_seen_at desc);

-- ── Dashboard sessions (opaque token; only its SHA-256 hash is stored) ───────────────────────────
create table public.dashboard_sessions (
  id          uuid primary key default gen_random_uuid(),
  token_hash  text not null unique,
  user_id     uuid not null references auth.users (id) on delete cascade,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null,
  revoked_at  timestamptz
);
create index dashboard_sessions_user_idx    on public.dashboard_sessions (user_id);
create index dashboard_sessions_expires_idx on public.dashboard_sessions (expires_at);

-- ── Failed-attempt counters for rate limiting / lockout ──────────────────────────────────────────
create table public.owner_auth_attempts (
  key            text primary key,           -- 'u:<user uuid>' or 'ip:<address>'
  failed_count   integer not null default 0,
  locked_until   timestamptz,
  last_failed_at timestamptz not null default now()
);

-- ── RLS: enabled + forced, deliberately no policies = deny all for anon/authenticated ────────────
alter table public.owner_settings       enable row level security;
alter table public.app_devices          enable row level security;
alter table public.app_events           enable row level security;
alter table public.ip_observations      enable row level security;
alter table public.dashboard_sessions   enable row level security;
alter table public.owner_auth_attempts  enable row level security;
alter table public.owner_settings       force row level security;
alter table public.app_devices          force row level security;
alter table public.app_events           force row level security;
alter table public.ip_observations      force row level security;
alter table public.dashboard_sessions   force row level security;
alter table public.owner_auth_attempts  force row level security;

revoke all on public.owner_settings, public.app_devices, public.app_events, public.ip_observations,
              public.dashboard_sessions, public.owner_auth_attempts from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;

-- ── Functions (service_role only) ─────────────────────────────────────────────────────────────────
-- Atomically records a device sighting, an event and the server-observed IP.
create function public.record_device_seen(
  p_install_id uuid, p_user_id uuid, p_model text, p_android text, p_app_version text,
  p_event text, p_ip inet
) returns uuid
language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_device uuid;
begin
  if p_event not in ('sign_in', 'app_open') then raise exception 'bad event'; end if;

  insert into app_devices (install_id, user_id, device_model, android_version, app_version)
  values (p_install_id, p_user_id, left(p_model, 80), left(p_android, 32), left(p_app_version, 32))
  on conflict (install_id) do update
    set user_id = excluded.user_id,
        device_model = excluded.device_model,
        android_version = excluded.android_version,
        app_version = excluded.app_version,
        last_seen_at = now()
  returning id into v_device;

  insert into app_events (user_id, device_id, event_type) values (p_user_id, v_device, p_event);

  if p_ip is not null then
    insert into ip_observations (ip, user_id, device_id) values (p_ip, p_user_id, v_device)
    on conflict (ip, user_id, device_id) do update
      set last_seen_at = now(), request_count = ip_observations.request_count + 1;
  end if;
  return v_device;
end $$;

-- Aggregate counts for the overview cards. Reads auth.users, hence security definer.
create function public.owner_summary() returns jsonb
language sql security definer set search_path = public, auth, pg_temp stable
as $$
  select jsonb_build_object(
    'total_accounts',            (select count(*) from auth.users),
    'accounts_active_30d',       (select count(distinct user_id) from app_devices where last_seen_at >= now() - interval '30 days'),
    'total_devices',             (select count(*) from app_devices),
    'devices_active_24h',        (select count(*) from app_devices where last_seen_at >= now() - interval '24 hours'),
    'devices_active_7d',         (select count(*) from app_devices where last_seen_at >= now() - interval '7 days'),
    'signins_24h',               (select count(*) from app_events where event_type = 'sign_in' and created_at >= now() - interval '24 hours'),
    'signins_7d',                (select count(*) from app_events where event_type = 'sign_in' and created_at >= now() - interval '7 days'),
    'app_opens_24h',             (select count(*) from app_events where event_type = 'app_open' and created_at >= now() - interval '24 hours'),
    'distinct_ips_30d',          (select count(distinct ip) from ip_observations where last_seen_at >= now() - interval '30 days')
  )
$$;

create function public.purge_expired_analytics() returns void
language plpgsql security definer set search_path = public, pg_temp
as $$
declare s owner_settings;
begin
  select * into s from owner_settings where id;
  delete from ip_observations     where last_seen_at < now() - make_interval(days => s.ip_retention_days);
  delete from app_events          where created_at   < now() - make_interval(days => s.event_retention_days);
  delete from dashboard_sessions  where expires_at   < now() - interval '1 day';
  delete from owner_auth_attempts where last_failed_at < now() - interval '1 day'
                                    and (locked_until is null or locked_until < now());
end $$;

revoke all on function public.record_device_seen(uuid, uuid, text, text, text, text, inet) from public, anon, authenticated;
revoke all on function public.owner_summary()           from public, anon, authenticated;
revoke all on function public.purge_expired_analytics() from public, anon, authenticated;
grant execute on function public.record_device_seen(uuid, uuid, text, text, text, text, inet) to service_role;
grant execute on function public.owner_summary()           to service_role;
grant execute on function public.purge_expired_analytics() to service_role;
grant select, insert, update, delete on public.owner_settings, public.app_devices, public.app_events,
      public.ip_observations, public.dashboard_sessions, public.owner_auth_attempts to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Daily retention purge.
create extension if not exists pg_cron;
select cron.schedule('purge-owner-analytics', '17 3 * * *', $$select public.purge_expired_analytics()$$);
